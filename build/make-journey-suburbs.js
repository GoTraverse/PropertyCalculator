/**
 * make-journey-suburbs.js — generates /journey-suburbs.json for the
 * /journey stop-4 suburb suggester.
 *
 * Joins data/market-current.json (verified CC BY 4.0 state-gov figures)
 * with data/suburbs.json (ABS names/slugs/population) so the journey can
 * suggest suburbs and search the dataset client-side.
 *
 * Data-honesty rules (CLAUDE.md):
 *  - sale medians only where a licensed suburb-geo source exists
 *    (VIC Valuer-General 2025 prelim; SA Valuer-General Q1 2026 metro);
 *  - rents are rents, never presented as prices;
 *  - NSW postcode-geo rents are EXCLUDED (postcode ≠ suburb);
 *  - only suburbs with pop ≥ 2000 and a real page slug are included, so
 *    every row links to an indexed suburb profile.
 *
 * Run manually after a market-current.json refresh:
 *   node build/make-journey-suburbs.js
 * Output is committed (same pattern as tools/market-medians.json).
 */
const fs = require('fs');
const path = require('path');

const market = require(path.join(__dirname, '..', 'data', 'market-current.json'));
const suburbs = require(path.join(__dirname, '..', 'data', 'suburbs.json'));

// state → { UPPERNAME → {slug, pop} }
const bySlug = {};
for (const s of suburbs) {
  const st = String(s.state || '').toLowerCase();
  if (!bySlug[st]) bySlug[st] = {};
  bySlug[st][String(s.suburb || '').toUpperCase()] = { slug: s.slug, pop: s.population || 0 };
}

const rows = [];
let skippedNoPage = 0;
for (const ST of Object.keys(market.data)) {
  const st = ST.toLowerCase();
  for (const NAME of Object.keys(market.data[ST])) {
    const rec = market.data[ST][NAME];
    const page = (bySlug[st] || {})[NAME];
    if (!page || !page.slug || page.pop < 2000) { skippedNoPage++; continue; }
    rows.push([
      st,
      // Title-case for display (market data ships uppercase)
      NAME.toLowerCase().replace(/(^|[\s\-'])([a-z])/g, (m, a, b) => a + b.toUpperCase()),
      page.slug,
      rec.price_house || 0,
      rec.price_unit || 0,
      rec.rent || 0,
    ]);
  }
}
rows.sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]));

const out = {
  v: 1,
  note: 'Generated by build/make-journey-suburbs.js from data/market-current.json (CC BY 4.0 state sources) + data/suburbs.json (ABS). Do not hand-edit.',
  asAt: {
    vic_price: 'Valuer-General Victoria, 2025 (preliminary)',
    sa_price: 'Valuer-General SA, Q1 2026 (metro Adelaide)',
    qld_rent: 'Residential Tenancies Authority (Qld), Mar 2026',
    sa_rent: 'Consumer & Business Services (SA), Jan–Mar 2026',
    tas_rent: 'Tasmanian rental bonds (DoJ), May 2025 – Apr 2026',
  },
  // row: [state, name, slug, price_house, price_unit, rent_weekly]
  rows,
};

fs.writeFileSync(path.join(__dirname, '..', 'journey-suburbs.json'), JSON.stringify(out));
const withPrice = rows.filter(r => r[3] || r[4]).length;
const withRent = rows.filter(r => r[5]).length;
console.log('journey-suburbs.json:', rows.length, 'suburbs (', withPrice, 'with sale medians,', withRent, 'with rents ),', skippedNoPage, 'skipped (no indexed page / pop < 2000)');
