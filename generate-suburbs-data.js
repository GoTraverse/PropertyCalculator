const stateNames = {
  QLD: 'Queensland', NSW: 'New South Wales', VIC: 'Victoria',
  WA: 'Western Australia', SA: 'South Australia', TAS: 'Tasmania',
  ACT: 'Australian Capital Territory', NT: 'Northern Territory'
};

function slug(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-+$/, '').replace(/^-+/, '');
}

// Generate plausible derived data
function makeSuburb(name, state, type, pop, distCBD, income) {
  const isRegional = type === 'regional';
  const isCoastal = type === 'coastal';
  const isInner = type === 'inner-city';
  const isOuter = type === 'outer-metro';

  // Population growth: inner/coastal higher, regional lower
  let popGrowth = isInner ? 5 + Math.round(Math.random() * 15) :
                  isCoastal ? 8 + Math.round(Math.random() * 18) :
                  isOuter ? 10 + Math.round(Math.random() * 20) :
                  isRegional ? 2 + Math.round(Math.random() * 10) :
                  6 + Math.round(Math.random() * 12);

  // School count based on population
  let schools = Math.max(1, Math.round(pop / 5000));
  if (schools > 40) schools = 35 + Math.round(Math.random() * 10);

  // Park count
  let parks = Math.max(1, Math.round(pop / 3000));
  if (parks > 50) parks = 40 + Math.round(Math.random() * 15);

  // Transport score: inner=8-10, middle=6-8, outer=4-6, regional=2-5
  let transport = isInner ? 8 + Math.round(Math.random() * 2) :
                  type === 'middle-ring' ? 6 + Math.round(Math.random() * 2) :
                  isOuter ? 4 + Math.round(Math.random() * 2) :
                  isCoastal ? 3 + Math.round(Math.random() * 3) :
                  2 + Math.round(Math.random() * 3);

  // Amenity score
  let amenity = isInner ? 8 + Math.round(Math.random() * 2) :
                type === 'middle-ring' ? 6 + Math.round(Math.random() * 2) :
                isCoastal ? 6 + Math.round(Math.random() * 3) :
                isOuter ? 5 + Math.round(Math.random() * 2) :
                3 + Math.round(Math.random() * 4);

  return {
    suburb: name,
    slug: slug(name),
    state: state,
    state_name: stateNames[state],
    population: pop,
    population_growth: popGrowth,
    median_household_income: income,
    distance_to_cbd: distCBD,
    suburb_type: type,
    school_count: schools,
    park_count: parks,
    transport_score: Math.min(10, transport),
    amenity_score: Math.min(10, amenity)
  };
}

// Generate all suburbs
const allSuburbs = [];
for (const [state, data] of Object.entries(states)) {
  for (const [name, type, pop, dist, income] of data.suburbs) {
    allSuburbs.push(makeSuburb(name, state, type, pop, dist, income));
  }
}

